export const lessons = courses.flatMap((c) =>
  c.lessons.map((l) => ({
    ...l,
    courseId: c.id,
    courseTitle: c.title,
    track: c.track,
  })),
);
export const findCourse = (id: string) => courses.find((c) => c.id === id);
export const findLesson = (id: string) => lessons.find((l) => l.id === id);
export function searchContent(query: string) {
  const q = query.trim().toLowerCase();
  return q
    ? lessons.filter((l) =>
        [l.title, l.explanation, l.example, l.courseTitle, l.track]
          .join(" ")
          .toLowerCase()
          .includes(q),
      )
    : [];
}
