import type { Course, Lesson, Level } from "./types";
export const tracks = [
  "Workforce Management",
  "Excel & Spreadsheets",
  "Data & Analytics",
  "Software Development",
  "AI & Intelligent Systems",
  "Automation & Delivery",
];
// Tuple fields: title, explanation, worked example, check, answer, distractor, applied assignment.
type Topic = [string, string, string, string, string, string, string];
const levels: Level[] = ["Beginner", "Intermediate", "Advanced"];
function course(
  id: string,
  title: string,
  track: number,
  description: string,
  source: string,
  prerequisites: string[],
  topics: Topic[],
  project: string,
): Course {
  return {
    id,
    title,
    track: tracks[track],
    description,
    prerequisites,
    status: "pilot",
    lessons: topics.map(
      (t, i): Lesson => ({
        id: `${id}-${i + 1}`,
        title: t[0],
        level: levels[i],
        objective: `Explain and apply ${t[0].toLowerCase()} to the worked scenario.`,
        explanation: t[1],
        example: t[2],
        question: t[3],
        answer: t[4],
        distractor: t[5],
        assignment: t[6],
        source,
      }),
    ),
    capstone: {
      title: project,
      brief: `Build ${project.toLowerCase()} using the three techniques practiced in this course. Submit your artifact, reproducible inputs, expected outputs, edge cases and a short explanation of the decisions you made. Use synthetic or public data only.`,
      rubric: [
        "Correctness: reproduce every worked example and explain differences.",
        "Robustness: demonstrate an ordinary case, a boundary case and an invalid input.",
        "Clarity: label inputs, outputs, assumptions and limitations.",
        "Reproducibility: include steps another learner can follow without your help.",
      ],
    },
  };
}
